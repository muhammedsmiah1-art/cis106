#!/bin/bash
 
echo "────────────────────────────────────────────────────────"
figlet "System"
echo "────────────────────────────────────────────────────────"
echo "DATE UTC:    $(date -u)"
echo "HOSTNAME:    $(hostname)"
echo "UPTIME:      $(uptime -p)"
echo "USER:        $(whoami)"
echo ""
 
echo "────────────────────────────────────────────────────────"
figlet "Memory"
echo "────────────────────────────────────────────────────────"
free -h
echo ""
 
echo "────────────────────────────────────────────────────────"
figlet "Disk"
echo "────────────────────────────────────────────────────────"
df -h /
